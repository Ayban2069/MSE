-- ============================================================
--  STEFF STORE — DATABASE SCHEMA (PostgreSQL / Supabase)
-- ============================================================

-- ------------------------------------------------------------
-- products
-- ------------------------------------------------------------
create table if not exists products (
    id              bigint generated by default as identity primary key,
    product_code    varchar(50)  not null unique,
    product_name    varchar(150) not null,
    category        varchar(100),
    price           numeric(10,2) not null default 0,
    cost            numeric(10,2) not null default 0,
    stock_quantity  integer not null default 0,
    reorder_level   integer not null default 5,
    created_at      timestamptz not null default now()
);

create index if not exists idx_products_product_name on products (product_name);
create index if not exists idx_products_category on products (category);

-- ------------------------------------------------------------
-- purchase_history — one row per item sold, grouped by receipt_number
-- ------------------------------------------------------------
create table if not exists purchase_history (
    id              bigint generated by default as identity primary key,
    receipt_number  varchar(30) not null,
    product_id      bigint references products(id),
    product_code    varchar(50),
    product_name    varchar(150),
    quantity        integer not null,
    unit_price      numeric(10,2) not null,
    unit_cost       numeric(10,2) not null,
    subtotal        numeric(10,2) not null,
    subtotal_cost   numeric(10,2) not null,
    total_amount    numeric(10,2) not null,
    cash_received   numeric(10,2),
    change_due      numeric(10,2),
    purchase_date   timestamptz not null default now()
);

create index if not exists idx_purchase_history_receipt_number on purchase_history (receipt_number);
create index if not exists idx_purchase_history_purchase_date on purchase_history (purchase_date);
create index if not exists idx_purchase_history_product_name on purchase_history (product_name);

-- ------------------------------------------------------------
-- users — login accounts (passwords stored as bcrypt hashes, never plain text)
-- ------------------------------------------------------------
create table if not exists users (
    id              bigint generated by default as identity primary key,
    username        varchar(50) not null unique,
    password_hash   varchar(255) not null,
    full_name       varchar(150),
    role            varchar(20) not null default 'cashier',
    created_at      timestamptz not null default now()
);

-- ============================================================
--  ROW LEVEL SECURITY
-- ============================================================
-- The app reads/writes these tables directly from the browser
-- using the Supabase anon key, so RLS must explicitly allow that
-- traffic. This setup is meant for a trusted, single-cashier
-- tool — not a public-facing page.

alter table products enable row level security;
alter table purchase_history enable row level security;
alter table users enable row level security;

-- products: read, add, edit, and let checkout deduct stock
create policy "anon can select products"
    on products for select to anon using (true);

create policy "anon can insert products"
    on products for insert to anon with check (true);

create policy "anon can update products"
    on products for update to anon using (true) with check (true);

-- purchase_history: read history/reports, insert new sales
create policy "anon can select purchase_history"
    on purchase_history for select to anon using (true);

create policy "anon can insert purchase_history"
    on purchase_history for insert to anon with check (true);

-- users: login reads and cashier self-registration. Privileged accounts
-- are created or edited from the Supabase dashboard.
create policy "anon can select users"
    on users for select to anon using (true);

create policy "anon can register users"
    on users for insert to anon with check (role = 'cashier');

-- Note: RLS policies control which ROWS are visible, not which
-- COLUMNS — a "select true" policy on users means the full row,
-- including password_hash, is fetchable with the anon key. That's
-- expected here: the login screen needs the hash to verify the
-- password with bcrypt in the browser. The hash itself is safe to
-- expose (bcrypt is one-way), but if that trade-off ever bothers
-- you, the fix is moving the check into a Postgres function (RPC)
-- so the hash never leaves the database — ask if you'd like that
-- built instead.
